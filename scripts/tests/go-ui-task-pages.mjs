import assert from 'node:assert/strict';
import {createTaskPages} from '../../web/src/state/task-pages.mjs';
import {combineTasks} from '../../web/src/state/aggregate.mjs';
import {mutationTopics} from '../../web/src/adapters/production.mjs';
const deferred=()=>{let resolve;const promise=new Promise(done=>resolve=done);return {promise,resolve};};
const held=deferred(),calls=[],progress=[],spaces=[{id:'a',control_id:'ca'},{id:'b',control_id:'cb'}];
const client={spaces,read:async(path,options)=>{
  calls.push({path,...options});const url=new URL(path,'http://fixture'),offset=Number(url.searchParams.get('offset')),space=options.space;
  if(space==='b')await held.promise;
  return {items:Array.from({length:50},(_,i)=>({id:space+(offset+i),assistant_id:'owner-'+i,updated_at_ms:10000-offset-i+(space==='b'?.5:0)})),total:5000,next_offset:offset+50,counts:{active:5000}};
}};
const read=createTaskPages(client),controller=new AbortController();
const pending=read({scope:'active',q:'',signal:controller.signal,onProgress:pages=>progress.push(pages)});
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(progress.length,1,'Fast Space is visible without waiting for the slow one');
assert.equal(calls.length,2,'First page reads once per Space, not once per assistant or backend page');
held.resolve();const first=await pending,result=combineTasks(first.pages);
assert.equal(result.total,10000);assert.equal(result.items.length,20);assert.equal(result.items[0]._space_id,'b');
assert.equal(result.next_offset,20,'Totals and pagination represent the full catalogue');
calls.length=0;const third=await read({scope:'active',q:'',offset:40,signal:controller.signal});
assert.equal(calls.length,4,'A later page reads only its sufficient prefix');
assert.ok(calls.every(call=>call.owner===''&&call.path.includes('/tasks/catalog?')),'Catalogues retain explicit Space without assistant fan-out');
assert.equal(combineTasks(third.pages,{offset:40}).items.length,20);
client.read=async()=>{throw Error('offline');};
const offline=await read({scope:'active',q:'',signal:controller.signal});assert.ok(offline.pages.every(page=>page.stale));
read.clear();await assert.rejects(read({scope:'active',q:'',signal:controller.signal}),/offline/);
const retired=deferred();client.read=async()=>retired.promise;
const cancelled=read({scope:'active',q:'new',signal:controller.signal});controller.abort();retired.resolve({items:[]});await assert.rejects(cancelled,{name:'AbortError'});
const late=deferred();client.read=async()=>late.promise;const bootRead=read({scope:'active',q:'boot',signal:new AbortController().signal});read.clear();late.resolve({items:[],total:0});await assert.rejects(bootRead,{name:'AbortError'},'Boot resets fence responses even when IO ignores cancellation');
assert.equal(mutationTopics('/api/v1/attachments',{action:'chunk'},{}),null,'Upload chunks do not invalidate display resources');
assert.equal(mutationTopics('/api/v1/providers/check',{},{}),null);
assert.deepEqual(mutationTopics('/api/v1/tasks/id/control',{},{}),['tasks','runner','usage']);
assert.ok(!mutationTopics('/api/v1/providers',{},{}).includes('machines'),'Provider saves keep machine inventory fresh');
console.log('Bounded task prefixes, progressive Spaces, global totals/order, cancellation, offline fencing and targeted invalidation passed');
