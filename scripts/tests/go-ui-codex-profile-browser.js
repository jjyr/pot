async page=>{
  const checks=[],assert=(value,message)=>{if(!value)throw Error(message);checks.push(message);},errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('dialog',dialog=>dialog.accept());
  const locale=value=>page.evaluate(value=>window.dispatchEvent(new CustomEvent('pot:preference',{detail:{key:'pot-go-preview-locale',value}})),value);
  await page.setViewportSize({width:1280,height:900});
  await page.goto(new URL('/scripts/tests/fixtures/codex-profile.html?locale=zh-CN',page.url()).href);
  await page.locator('.role-assistant').filter({hasText:'运行在 Codex'}).waitFor();
  const original=await page.locator('.assistant-row .avatar-image').getAttribute('src');
  assert(original.startsWith('data:image/png;base64,'),'Fresh Codex directory has a saved avatar');
  assert(await page.locator('.window-title .avatar-image').getAttribute('src')===original,'Header and directory share the same avatar');
  const welcome=await page.locator('.role-assistant').innerText();
  assert(welcome.includes('换个名字、换张头像'),'Welcome includes ordinary assistant guidance');
  const dismiss=page.getByRole('button',{name:'暂时不用',exact:true});if(await dismiss.count())await dismiss.click();
  await page.locator('#pot-composer').fill('Keep my draft');
  await page.getByRole('button',{name:'助手设置',exact:true}).click();
  await page.getByRole('textbox',{name:'名称',exact:true}).fill('Codex profile test');
  assert(await page.locator('.editor-form select').count()===0,'Linked settings contain no local Provider or model controls');
  await locale('en');
  assert(await page.getByRole('textbox',{name:'Name',exact:true}).inputValue()==='Codex profile test','Locale switch preserves the name draft');
  assert(await page.getByRole('button',{name:'Change avatar',exact:true}).isVisible(),'Avatar controls translate live');
  await page.locator('.editor-form input[type=file]').setInputFiles('web/src/assets/PotCompanion.png');
  await page.waitForFunction(original=>document.querySelector('.editor-fields > .avatar img')?.src!==original,original);
  const custom=await page.locator('.editor-fields > .avatar img').getAttribute('src');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.locator('.assistant-title').filter({hasText:'Codex profile test'}).waitFor();
  assert(await page.locator('.assistant-row .avatar-image').getAttribute('src')===custom,'Uploaded avatar persists through peer editing and directory refresh');
  assert(await page.locator('#pot-composer').inputValue()==='Keep my draft','Profile editing preserves the chat draft');
  assert(await page.locator('.role-assistant').innerText()===welcome,'Rename and locale changes preserve the original welcome');
  await page.getByRole('button',{name:'Assistant settings',exact:true}).click();
  await page.getByRole('button',{name:'Restore default avatar',exact:true}).click();
  await page.waitForFunction(original=>document.querySelector('.editor-fields > .avatar img')?.src===original,original);
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.locator('.window-title .avatar-image').waitFor();
  assert(await page.locator('.window-title .avatar-image').getAttribute('src')===original,'Restore default retains the original character after rename');
  await page.reload();await page.locator('.assistant-row .avatar-image').waitFor();
  assert(await page.locator('.assistant-row .avatar-image').getAttribute('src')===original,'Fresh client retains the saved profile');
  assert(await page.locator('.role-assistant').count()===1,'Reload does not duplicate the introduction');
  await page.setViewportSize({width:393,height:852});await locale('zh-CN');
  await page.getByRole('button',{name:'助手设置',exact:true}).click();
  await page.getByRole('textbox',{name:'名称',exact:true}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile profile editor has no horizontal overflow');
  assert(await page.getByRole('button',{name:'更换头像',exact:true}).isVisible(),'Mobile exposes translated avatar editing');
  assert(errors.length===0,'No browser script errors: '+errors.join('; '));
  return {checks,modelCalls:0};
}
