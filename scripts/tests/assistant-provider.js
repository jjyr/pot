// Playwright CLI run-code expression. Uses disposable shared-ui-fixture --pages only.
async (page) => {
  const base='http://127.0.0.1:17908';
  const get=async path=>(await page.request.get(base+path)).json();
  if((await get('/api/v1/runtime')).runtime_id!=='fixture')throw Error('Expected isolated UI fixture');
  const writesBefore=(await get('/__fixture/writes')).length;
  const assistantsBefore=(await get('/api/v1/assistants')).assistants.length;
  const providers=await get('/api/v1/providers');
  const definitions=(await get('/api/v1/agent')).profiles;
  const defaultModel=definitions.find(p=>p.id===providers.default_provider_id).model;
  const wait=()=>page.waitForTimeout(500);
  let checks=0;const assert=(ok,message)=>{if(!ok)throw Error(message);checks++;};
  const input=async(x,y)=>{await page.mouse.click(x,y);await page.waitForTimeout(100);return page.locator('textarea').inputValue();};
  const set=async(x,y,text)=>{await page.mouse.click(x,y);await page.keyboard.press('Meta+A');await page.keyboard.type(text);};
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.evaluate(()=>{sessionStorage.removeItem('pot-ui-errors');localStorage.setItem('pot-locale','en');localStorage.setItem('pot-appearance','1');});
  await page.setViewportSize({width:1280,height:800});
  await page.goto(base+'/?page=chat&assistant=main');
  await wait();
  await page.mouse.click(250,69);await wait();
  assert(await input(500,399)===defaultModel,'Creation must select the Provider concrete default model');
  await set(500,237,'Provider flow preview');
  await page.screenshot({path:'output/playwright/issue61-new-assistant.png'});
  await page.mouse.click(668,433);await wait();
  await page.mouse.click(670,484);await wait();
  await set(650,86,'fixture-only-key');await set(650,149,'opus5.5');
  await set(650,193,'Nested Provider');await set(650,237,'https://example.invalid/v1');
  await page.mouse.click(997,762);await wait();
  assert((await get('/api/v1/assistants')).assistants.length===assistantsBefore,'Provider setup must not create an assistant');
  assert(await input(500,237)==='Provider flow preview','Nested Provider setup must preserve the new assistant draft');
  assert(await input(500,399)==='opus5.5','The newly configured Provider must be selected with its concrete model');
  await page.screenshot({path:'output/playwright/issue61-nested-return.png'});
  await page.mouse.click(530,526);await wait();
  const writes=(await get('/__fixture/writes')).slice(writesBefore);
  const created=writes.find(w=>w.path==='/api/v1/assistants');
  const connection=writes.find(w=>w.path.endsWith('/providers'));
  assert(created?.body.name==='Provider flow preview','Create must submit the preserved assistant name');
  assert(created.body.configuration.model==='opus5.5','Create must submit a concrete model ID');
  assert(created.body.configuration.provider_id===connection.body.profile_id,'Create must reference the new shared Provider');
  assert(!writes.some(w=>w.path.endsWith('/messages')||w.path.endsWith('/providers/check')),'Form saves must not call models');
  const id=(await get('/api/v1/assistants')).assistants.at(-1).id;
  assert(page.url().includes('assistant='+id),'Creation must open the new assistant');
  await page.setViewportSize({width:390,height:844});await wait();
  await page.screenshot({path:'output/playwright/issue61-phone-chat.png'});
  await page.mouse.click(355,22);await wait();
  await page.mouse.click(250,74);await wait();
  await page.screenshot({path:'output/playwright/issue61-phone-editor.png'});
  await set(120,118,'Saved preview');await set(90,302,'assistant-revised');
  await page.mouse.click(117,526);await wait();
  await page.mouse.click(355,22);await wait();await page.mouse.click(250,74);await wait();
  assert(await input(120,118)==='Saved preview','Acknowledged saves must refresh the assistant name');
  assert(await input(90,302)==='assistant-revised','Reopening must show the saved assistant model');
  await page.screenshot({path:'output/playwright/issue61-phone-editor.png'});
  assert(errors.length===0,errors.join('\n'));
  return {checks,defaultModel,selectedModel:'opus5.5',assistant:id,modelCalls:0};
}
