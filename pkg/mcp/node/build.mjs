import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=dirname(fileURLToPath(import.meta.url));
const result=await build({absWorkingDir:root,entryPoints:['runtime.mjs'],bundle:true,platform:'node',format:'esm',target:'node22',minify:true,legalComments:'none',metafile:true,write:false});
const packages=new Set();
for(const file of Object.keys(result.metafile.inputs)){
 const parts=file.split('/');const i=parts.lastIndexOf('node_modules');if(i<0)continue;
 packages.add(parts.slice(0,i+1+(parts[i+1].startsWith('@')?2:1)).join('/'));
}
const notices=[];
for(const directory of [...packages].sort()){
 const manifest=JSON.parse(await readFile(join(root,directory,'package.json'),'utf8'));
 let license;for(const name of ['LICENSE','LICENSE.txt','LICENSE.md','license','license.txt']){try{license=await readFile(join(root,directory,name),'utf8');break;}catch{}}
 if(!license)throw Error('Missing license for '+manifest.name);
 notices.push(manifest.name+' '+manifest.version+'\n'+license.replace(/[ \t]+$/gm,''));
}
const banner='// Generated by npm ci && npm run build in pkg/mcp/node. See NOTICE.txt.\n';
for(const [name,content] of [['node-runtime.mjs',banner+result.outputFiles[0].text],['NOTICE.txt',notices.join('\n\n')+'\n']]){
 const path=resolve(root,'../assets',name);
 if(process.argv.includes('--check')){
  if(await readFile(path,'utf8')!==content)throw Error('Outdated MCP asset: '+name);
 }else await writeFile(path,content);
}
